import json, os, re, subprocess, sys

DB = sys.argv[1] if len(sys.argv) > 1 else "postgresql://postgres:postgres@127.0.0.1:54322/postgres"
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def q(sql):
    out = subprocess.run(["psql", DB, "-qAt", "-c", f"select coalesce(json_agg(t), '[]') from ({sql}) t"], capture_output=True, text=True, check=True).stdout
    return json.loads(out.strip() or "[]")


def esc(s):
    return (s or "").replace("|", "\\|").replace("\n", " ").strip()


def short(s, n=220):
    s = re.sub(r"\s+", " ", s or "").strip()
    return s if len(s) <= n else s[: n - 1] + "…"


tests_dir = os.path.join(ROOT, "supabase", "tests")
tests = {f: open(os.path.join(tests_dir, f), encoding="utf8").read() for f in sorted(os.listdir(tests_dir)) if f.endswith(".sql")}


def evidence(table):
    hits = [f for f, body in tests.items() if re.search(rf"\b{re.escape(table)}\b", body)]
    return ", ".join(hits[:3]) + (f" (+{len(hits) - 3})" if len(hits) > 3 else "") if hits else "none found"


FN = re.compile(r"\b([a-z_][a-z0-9_]*)\s*\(")
NOT_FN = {"select", "exists", "array", "coalesce", "any", "all", "in", "and", "or", "not", "lower", "upper", "trim", "length", "now", "cardinality", "jsonb_build_object", "case", "count", "extract", "split_part", "storage", "foldername", "date", "nullif", "greatest", "least"}


def functions_in(*parts):
    names = set()
    for p in parts:
        for m in FN.finditer(p or ""):
            n = m.group(1)
            if n not in NOT_FN:
                names.add(n)
    return ", ".join(sorted(names)) or "none"


def concerns(p):
    c = []
    roles = p["roles"] or []
    using, check = p["qual"] or "", p["with_check"] or ""
    if "public" in roles or "anon" in roles:
        c.append("applies to signed-out (anon/public) role")
    if using.strip() == "true" or check.strip() == "true":
        c.append("condition is `true` (everyone in the role)")
    if p["cmd"] in ("INSERT",) and not check:
        c.append("insert without WITH CHECK")
    body = (using + " " + check)
    if re.fullmatch(r"\s*\(*\s*\(?\s*select\s+(public\.)?is_member\(\)( as is_member)?\s*\)?\s*\)*\s*", body.strip(), re.I) or body.strip() in ("is_member()", "(SELECT is_member() AS is_member)"):
        c.append("every signed-in member: check the table holds nothing sensitive")
    if "auth.uid()" in body and "select auth.uid()" not in body.lower() and "( select auth.uid()" not in body.lower():
        c.append("auth.uid() not wrapped (Stage 1 performance form)")
    return "; ".join(c) or "—"


# ---------------------------------------------------------------- SEC-002
pol = q("""
  select n.nspname as schema, c.relname as tbl, p.polname as name,
         case p.polcmd when 'r' then 'SELECT' when 'a' then 'INSERT' when 'w' then 'UPDATE' when 'd' then 'DELETE' else 'ALL' end as cmd,
         case when p.polpermissive then 'PERMISSIVE' else 'RESTRICTIVE' end as kind,
         (select coalesce(array_agg(case when r = 0 then 'public' else pg_get_userbyid(r) end order by 1), '{}') from unnest(p.polroles) r) as roles,
         pg_get_expr(p.polqual, p.polrelid) as qual, pg_get_expr(p.polwithcheck, p.polrelid) as with_check
    from pg_policy p join pg_class c on c.oid = p.polrelid join pg_namespace n on n.oid = c.relnamespace
   where n.nspname in ('public', 'storage') order by 1, 2, 4, 3""")
tables = q("""select t.tablename as tbl, t.rowsecurity as rls,
                     (select count(*) from pg_policies p where p.schemaname = 'public' and p.tablename = t.tablename) as policies
                from pg_tables t where t.schemaname = 'public' order by 1""")
definers = q("""select p.proname as name, pg_get_function_identity_arguments(p.oid) as args,
                       p.prorettype = 'trigger'::regtype as is_trigger,
                       has_function_privilege('anon', p.oid, 'execute') as anon,
                       has_function_privilege('authenticated', p.oid, 'execute') as auth
                  from pg_proc p where p.pronamespace = 'public'::regnamespace and p.prosecdef order by 1, 2""")

lines = ["# SEC-002 appendix A: every current policy (generated)", "",
         "Generated by `docs/tools/generate-from-database.py` from the local database built from `supabase/migrations` (updates to 90). **Facts only**: the intended access is the policy's own name; the concerns column is automatic pattern-matching for review, not a finding. Evidence = test files that mention the table.", "",
         f"Policies: {len(pol)} ({sum(1 for p in pol if p['schema'] == 'public')} on public tables, {sum(1 for p in pol if p['schema'] == 'storage')} on file storage).", ""]
for schema in ("public", "storage"):
    lines += [f"## {schema}", "", "| Table | Policy (intended access) | Command | Type | Roles | USING | WITH CHECK | Functions referenced | Automatic concerns | Test evidence |", "|---|---|---|---|---|---|---|---|---|---|"]
    for p in [x for x in pol if x["schema"] == schema]:
        lines.append("| " + " | ".join([
            f"`{p['tbl']}`", esc(p["name"]), p["cmd"], p["kind"], ", ".join(p["roles"]),
            f"`{esc(short(p['qual']))}`" if p["qual"] else "—", f"`{esc(short(p['with_check']))}`" if p["with_check"] else "—",
            esc(functions_in(p["qual"], p["with_check"])), esc(concerns(p)), esc(evidence(p["tbl"]) if schema == "public" else "storage tests: " + evidence("storage.objects")),
        ]) + " |")
    lines.append("")
lines += ["## Tables with row level security on and no policy (no direct access through the API)", ""]
lines += [f"- `{t['tbl']}`" for t in tables if t["rls"] and t["policies"] == 0] + [""]
lines += ["## Tables without row level security", ""]
lines += ([f"- `{t['tbl']}`" for t in tables if not t["rls"]] or ["- none"]) + [""]
lines += ["## SECURITY DEFINER functions", "", f"{len(definers)} functions. Trigger functions can't be called directly. 'anon' = executable by signed-out callers (most such functions return false or nothing without a signed-in user; each needs review).", "",
          "| Function | Arguments | Trigger | anon can execute | signed-in can execute |", "|---|---|---|---|---|"]
for d in definers:
    lines.append(f"| `{d['name']}` | {esc(d['args']) or '—'} | {'yes' if d['is_trigger'] else 'no'} | {'yes' if d['anon'] else 'no'} | {'yes' if d['auth'] else 'no'} |")
open(os.path.join(ROOT, "docs/04-security-and-privacy/SEC-002-appendix-a-policies.md"), "w").write("\n".join(lines) + "\n")

# ---------------------------------------------------------------- DB-001
cols = q("""select c.table_name as tbl, count(*) as n from information_schema.columns c where c.table_schema = 'public' group by 1""")
ncols = {c["tbl"]: c["n"] for c in cols}
cons = q("""select c.conrelid::regclass::text as tbl, c.contype as type, c.conname as name, pg_get_constraintdef(c.oid) as def
              from pg_constraint c join pg_namespace n on n.oid = c.connamespace
             where n.nspname = 'public' and c.contype in ('p', 'f', 'u') order by 1, 2, 3""")
trg = q("""select c.relname as tbl, t.tgname as name, p.proname as fn
             from pg_trigger t join pg_class c on c.oid = t.tgrelid join pg_namespace n on n.oid = c.relnamespace join pg_proc p on p.oid = t.tgfoid
            where n.nspname = 'public' and not t.tgisinternal order by 1, 2""")
idx = q("""select count(*) as n from pg_indexes where schemaname = 'public'""")[0]["n"]
lines = ["# DB-001 appendix A: every table (generated)", "",
         "Generated by `docs/tools/generate-from-database.py` from the local database built from `supabase/migrations` (updates to 90). Primary key (PK), foreign keys (FK, `→ table`), unique constraints, triggers, row level security and policy count.", "",
         f"Tables: {len(tables)}. Indexes: {idx}. Triggers: {len(trg)}.", "",
         "| Table | Columns | PK | References (FK) | Unique | Triggers | RLS | Policies |", "|---|---|---|---|---|---|---|---|"]
for t in tables:
    name = t["tbl"]
    mine = [c for c in cons if c["tbl"] in (name, f"public.{name}")]
    pk = "; ".join(re.sub(r"PRIMARY KEY ", "", c["def"]) for c in mine if c["type"] == "p") or "—"
    fks = sorted({re.search(r"REFERENCES ([a-z_.]+)", c["def"]).group(1).replace("public.", "") for c in mine if c["type"] == "f"})
    uq = "; ".join(re.sub(r"UNIQUE ", "", c["def"]) for c in mine if c["type"] == "u") or "—"
    tg = ", ".join(sorted({x["fn"] for x in trg if x["tbl"] == name})) or "—"
    lines.append(f"| `{name}` | {ncols.get(name, '?')} | {esc(pk)} | {esc(', '.join(fks)) or '—'} | {esc(uq)} | {esc(tg)} | {'on' if t['rls'] else '**off**'} | {t['policies']} |")
open(os.path.join(ROOT, "docs/03-database-and-data/DB-001-appendix-a-tables.md"), "w").write("\n".join(lines) + "\n")

# ---------------------------------------------------------------- MOD-001
mods = q("""select id, parent_id, category, label, sensitivity, delegable, status, actions, legacy_kind, legacy_area
              from public.app_modules where id not like 'cat\\_%' order by category, coalesce(parent_id, id), id""")
code = open(os.path.join(ROOT, "src/lib/modules.ts"), encoding="utf8").read()
href = {m.group(1): m.group(2) for m in re.finditer(r'\{ id: "([a-z_.]+)", category:[^\n]*?href: "([^"]+)"', code)}
in_code = set(re.findall(r'\{ id: "([a-z_.]+)", category:', code))
app = os.path.join(ROOT, "src", "app")


def route_exists(h):
    if not h:
        return "no page"
    path = h.split("?")[0].strip("/")
    for base in (os.path.join(app, "(portal)"), app):
        d = os.path.join(base, path) if path else base
        if os.path.exists(os.path.join(d, "page.tsx")):
            return "yes"
    return "**not found**"


lines = ["# MOD-001 appendix A: catalogue as defined (generated)", "",
         "Generated by `docs/tools/generate-from-database.py` from `public.app_modules` (local database built from the migrations) and `src/lib/modules.ts`. Menu **categories** are shown as they are: they're menu groups, not business Function Groups.", "",
         f"Modules: {len(mods)} in the database; {len(in_code)} in `src/lib/modules.ts`; missing from code: {', '.join(sorted({m['id'] for m in mods} - in_code)) or 'none'}; missing from database: {', '.join(sorted(in_code - {m['id'] for m in mods})) or 'none'}.", "",
         "| Module ID | Name | Parent | Menu category | Actions | Sensitivity | Delegable | Status | Legacy link | Page | Page exists |", "|---|---|---|---|---|---|---|---|---|---|---|"]
for m in mods:
    h = href.get(m["id"], "")
    legacy = f"{m['legacy_kind']}: {m['legacy_area']}" if m["legacy_kind"] else "—"
    lines.append(f"| `{m['id']}` | {esc(m['label'])} | {('`' + m['parent_id'] + '`') if m['parent_id'] else '—'} | {m['category']} | {', '.join(m['actions'])} | {m['sensitivity']} | {'yes' if m['delegable'] else 'no'} | {m['status']} | {legacy} | {h or '—'} | {route_exists(h)} |")
open(os.path.join(ROOT, "docs/01-product/MOD-001-appendix-a-catalogue.md"), "w").write("\n".join(lines) + "\n")
print("written: SEC-002, DB-001 and MOD-001 appendices")
